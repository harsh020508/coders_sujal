class I18nManager {
  constructor() {
    this._listeners = new Set();
  }

  getLanguage() {
    return Settings.get('general.language', 'en');
  }

  setLanguage(lang) {
    if (!SUPPORTED_LANGUAGES.some(l => l.code === lang)) {
      lang = 'en';
    }
    Settings.set('general.language', lang);
    Settings.save();

    if (typeof document !== 'undefined') {
      document.documentElement.setAttribute('lang', lang);
      document.querySelectorAll('select.lang-picker, select[id*="lang"], select[id*="language"]').forEach(sel => {
        if (sel.value !== lang) sel.value = lang;
      });
    }

    if (typeof window !== 'undefined' && typeof window.dispatchEvent === 'function') {
      window.dispatchEvent(new CustomEvent('locakaam:language-changed', { detail: { language: lang } }));
      window.dispatchEvent(new CustomEvent('localkaam:language-changed', { detail: { language: lang } }));
    }

    this._listeners.forEach(fn => {
      try { fn(lang); } catch (e) {}
    });

    return lang;
  }

  t(key, fallback = '') {
    const lang = this.getLanguage();
    if (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) {
      return TRANSLATIONS[lang][key];
    }
    if (TRANSLATIONS.en && TRANSLATIONS.en[key]) {
      return TRANSLATIONS.en[key];
    }
    return fallback || key;
  }

  tCatName(catId, fallback = '') {
    const key = `cat_${catId}`;
    return this.t(key, fallback || catId);
  }

  tCatDesc(catId, fallback = '') {
    const key = `cat_${catId}_desc`;
    return this.t(key, fallback || '');
  }

  tStatus(status) {
    const map = {
      'Pending confirmation': 'status_pending',
      'Confirmed': 'status_confirmed',
      'Worker en route': 'status_en_route',
      'Worker arrived': 'status_arrived',
      'Job in progress': 'status_in_progress',
      'Job completed': 'status_completed',
      'Cancelled': 'status_cancelled',
      'Disputed': 'status_disputed'
    };
    const key = map[status];
    return key ? this.t(key, status) : status;
  }

  tLocality(locId, fallback = '') {
    const key = `loc_${locId}`;
    return this.t(key, fallback || locId);
  }

  translateDOM(root = document.body) {
    if (!root) return;
    const lang = this.getLanguage();
    if (lang === 'en') return;

    const dict = PHRASE_DICTIONARY[lang];
    if (!dict) return;

    const keys = Object.keys(dict).sort((a, b) => b.length - a.length);

    // Pre-pass: Handle elements with <br> where the overall phrase is split by linebreaks
    const candidateElements = [];
    if (root.matches && root.matches('h1, h2, h3, h4, h5, h6, p, li, span, button, a')) {
      candidateElements.push(root);
    }
    if (root.querySelectorAll) {
      root.querySelectorAll('h1, h2, h3, h4, h5, h6, p, li, span, button, a').forEach(el => candidateElements.push(el));
    }

    candidateElements.forEach(el => {
      if (el.innerHTML && el.innerHTML.includes('<br') && (!el.querySelector || !el.querySelector('select, input, textarea'))) {
        const raw = el.innerHTML.replace(/<br\s*\/?>/gi, '\n').replace(/\u00A0/g, ' ').trim();
        const norm = raw.replace(/\s+/g, ' ');
        if (dict[raw]) {
          el.innerHTML = dict[raw].replace(/\n/g, '<br>');
        } else if (dict[norm]) {
          el.innerHTML = dict[norm].replace(/\n/g, '<br>');
        }
      }
    });

    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, null, false);
    let node;
    const toReplace = [];
    while ((node = walker.nextNode())) {
      const parent = node.parentElement;
      const parentTag = parent ? parent.tagName.toLowerCase() : '';
      if (['script', 'style', 'code', 'pre'].includes(parentTag)) continue;
      if (parent && parent.classList && (parent.classList.contains('settings-kbd') || parent.classList.contains('mono-code'))) continue;
      if (parentTag === 'option' && parent.closest && parent.closest('.lang-picker')) continue;

      let text = (node.nodeValue || '').replace(/\u00A0/g, ' ');
      const trimmed = text.trim();
      if (!trimmed) continue;

      // 1. Exact match
      if (dict[trimmed]) {
        toReplace.push({ node, text: text.replace(trimmed, dict[trimmed]) });
        continue;
      }

      // 2. Whitespace normalized match
      const normalized = trimmed.replace(/\s+/g, ' ');
      if (dict[normalized]) {
        toReplace.push({ node, text: text.replace(trimmed, dict[normalized]) });
        continue;
      }

      // 3. Stripped quotation marks match (e.g. testimonials wrapped in quotes: "The electrician...")
      const strippedQuotes = trimmed.replace(/^[\"\'“\"«]+/, '').replace(/[\"\'”\"»]+$/, '').trim();
      if (strippedQuotes && strippedQuotes !== trimmed) {
        const normStripped = strippedQuotes.replace(/\s+/g, ' ');
        if (dict[strippedQuotes]) {
          toReplace.push({ node, text: text.replace(strippedQuotes, dict[strippedQuotes]) });
          continue;
        } else if (dict[normStripped]) {
          toReplace.push({ node, text: text.replace(strippedQuotes, dict[normStripped]) });
          continue;
        }
      }

      // 4. Phrase or word-boundary matches
      let modified = false;
      for (const enKey of keys) {
        if (enKey.length < 3) continue;
        if (/\s/.test(enKey)) {
          if (text.includes(enKey)) {
            text = text.split(enKey).join(dict[enKey]);
            modified = true;
          }
        } else {
          const escaped = enKey.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
          const regex = new RegExp('\\b' + escaped + '\\b', 'g');
          if (regex.test(text)) {
            text = text.replace(regex, dict[enKey]);
            modified = true;
          }
        }
      }
      if (modified) {
        toReplace.push({ node, text });
      }
    }

    toReplace.forEach(item => {
      item.node.nodeValue = item.text;
    });

    // Translate input placeholders
    if (root.querySelectorAll) {
      root.querySelectorAll('input[placeholder], textarea[placeholder]').forEach(el => {
        const ph = (el.getAttribute('placeholder') || '').replace(/\u00A0/g, ' ');
        if (!ph) return;
        if (dict[ph]) {
          el.setAttribute('placeholder', dict[ph]);
        } else {
          const norm = ph.trim().replace(/\s+/g, ' ');
          if (dict[norm]) {
            el.setAttribute('placeholder', dict[norm]);
          } else {
            for (const enKey of keys) {
              if (ph.includes(enKey)) {
                el.setAttribute('placeholder', ph.split(enKey).join(dict[enKey]));
                break;
              }
            }
          }
        }
      });

      // Translate titles and aria-labels
      root.querySelectorAll('[title], [aria-label]').forEach(el => {
        const title = el.getAttribute('title');
        if (title) {
          const normTitle = title.trim().replace(/\u00A0/g, ' ').replace(/\s+/g, ' ');
          if (dict[title]) el.setAttribute('title', dict[title]);
          else if (dict[normTitle]) el.setAttribute('title', dict[normTitle]);
        }
        const aria = el.getAttribute('aria-label');
        if (aria) {
          const normAria = aria.trim().replace(/\u00A0/g, ' ').replace(/\s+/g, ' ');
          if (dict[aria]) el.setAttribute('aria-label', dict[aria]);
          else if (dict[normAria]) el.setAttribute('aria-label', dict[normAria]);
        }
      });
    }
  }

  renderLanguageSelector(id = 'nav-lang-picker', extraClass = '') {
    const current = this.getLanguage();
    return `
      <select id="${id}" class="lang-picker ${extraClass}" aria-label="Select display language">
        ${SUPPORTED_LANGUAGES.map(l => `
          <option value="${l.code}" ${l.code === current ? 'selected' : ''}>
            🌐 ${l.nativeName} (${l.name})
          </option>
        `).join('')}
      </select>
    `;
  }
}

export const i18n = new I18nManager();
export const t = (key, fallback) => i18n.t(key, fallback);
