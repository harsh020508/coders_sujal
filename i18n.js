class I18nManager {
  constructor() {
    this._listeners = new Set();
  }

  getLanguage() {
    return Settings.get('general.language', 'en');
  }

  setLanguage(lang) {
    if (!SUPPORTED_LANGUAGES.some(l => l.code === lang)) {
      lang = 'en';
    }
    Settings.set('general.language', lang);
    Settings.save();

    if (typeof document !== 'undefined') {
      document.documentElement.setAttribute('lang', lang);
    }

    if (typeof window !== 'undefined') {
      window.dispatchEvent(new CustomEvent('locakaam:language-changed', { detail: { language: lang } }));
    }

    return lang;
  }

  t(key, fallback = '') {
    const lang = this.getLanguage();
    if (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) {
      return TRANSLATIONS[lang][key];
    }
    if (TRANSLATIONS.en && TRANSLATIONS.en[key]) {
      return TRANSLATIONS.en[key];
    }
    return fallback || key;
  }

  tCatName(catId, fallback = '') {
    const key = `cat_${catId}`;
    return this.t(key, fallback || catId);
  }

  tCatDesc(catId, fallback = '') {
    const key = `cat_${catId}_desc`;
    return this.t(key, fallback || '');
  }

  tStatus(status) {
    const map = {
      'Pending confirmation': 'status_pending',
      'Confirmed': 'status_confirmed',
      'Worker en route': 'status_en_route',
      'Worker arrived': 'status_arrived',
      'Job in progress': 'status_in_progress',
      'Job completed': 'status_completed',
      'Cancelled': 'status_cancelled',
      'Disputed': 'status_disputed'
    };
    const key = map[status];
    return key ? this.t(key, status) : status;
  }

  tLocality(locId, fallback = '') {
    const key = `loc_${locId}`;
    return this.t(key, fallback || locId);
  }

  translateDOM(root = document.body) {
    if (!root) return;
    const lang = this.getLanguage();
    if (lang === 'en') return;

    const dict = PHRASE_DICTIONARY[lang];
    if (!dict) return;

    // Sort keys by length descending so longer phrases match before shorter sub-words
    const keys = Object.keys(dict).sort((a, b) => b.length - a.length);

    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, null, false);
    let node;
    const toReplace = [];
    while ((node = walker.nextNode())) {
      const parentTag = node.parentElement ? node.parentElement.tagName.toLowerCase() : '';
      if (['script', 'style', 'code', 'pre'].includes(parentTag)) continue;

      let text = node.nodeValue;
      const trimmed = text.trim();
      if (!trimmed) continue;

      if (dict[trimmed]) {
        toReplace.push({ node, text: text.replace(trimmed, dict[trimmed]) });
        continue;
      }

      // Check substring matches
      let modified = false;
      for (const enKey of keys) {
        if (enKey.length >= 2 && text.includes(enKey)) {
          text = text.split(enKey).join(dict[enKey]);
          modified = true;
        }
      }
      if (modified) {
        toReplace.push({ node, text });
      }
    }

    toReplace.forEach(item => {
      item.node.nodeValue = item.text;
    });

    // Translate input placeholders
    root.querySelectorAll('input[placeholder], textarea[placeholder]').forEach(el => {
      const ph = el.getAttribute('placeholder');
      if (!ph) return;
      if (dict[ph]) {
        el.setAttribute('placeholder', dict[ph]);
      } else {
        for (const enKey of keys) {
          if (ph.includes(enKey)) {
            el.setAttribute('placeholder', ph.split(enKey).join(dict[enKey]));
            break;
          }
        }
      }
    });

    // Translate titles
    root.querySelectorAll('[title]').forEach(el => {
      const title = el.getAttribute('title');
      if (title && dict[title]) {
        el.setAttribute('title', dict[title]);
      }
    });
  }

  renderLanguageSelector(id = 'nav-lang-picker', extraClass = '') {
    const current = this.getLanguage();
    return `
      <select id="${id}" class="lang-picker ${extraClass}" aria-label="Select display language">
        ${SUPPORTED_LANGUAGES.map(l => `
          <option value="${l.code}" ${l.code === current ? 'selected' : ''}>
            🌐 ${l.nativeName} (${l.name})
          </option>
        `).join('')}
      </select>
    `;
  }
}

export const i18n = new I18nManager();
export const t = (key, fallback) => i18n.t(key, fallback);
